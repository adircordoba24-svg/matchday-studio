// ---------------- בניית הפרומפט ----------------
export function fillTemplate(tpl, vars) {
  return String(tpl).replace(/\{\{\s*([A-Z_]+)\s*\}\}/g, (_, k) => (k in vars ? String(vars[k]) : ""));
}

export function buildPromptVars(o) {
  const style = byId(STYLES, o.styleId) || { code: "", en: o.styleName || "" };
  const n = Number(o.photoCount) || 1;
  const files = Array.from({ length: n }, (_, i) => `photo-${i + 1}.jpg`).join(", ");
  const showChannel = o.broadcast === "yes" && !!o.broadcastChannel;
  const L = logoInfo(o);
  return {
    PLAYER: o.player,
    NUMBER: o.number || "אין (השמט את המספר מהעיצוב)",
    TEAM: o.team,
    OPPONENT: o.opponent,
    COMPETITION: o.competitionLabel,
    VENUE: o.venue,
    TIME: o.time,
    BROADCAST: o.broadcast === "yes" ? "יש שידור" : "אין שידור",
    CHANNEL: showChannel ? o.broadcastChannel : "",
    CHANNEL_LINE: showChannel ? `ערוץ: ${o.broadcastChannel}\n` : "",
    LAYOUT: LAYOUT_HE[o.photoLayout] || LAYOUT_HE.designer,
    PHOTO_COUNT: n,
    PHOTO_FILES: files,
    NOTES: o.notes ? o.notes : "אין.",
    STYLE_CODE: style.code,
    STYLE_NAME: style.en,
    LOGO_AGENT: buildLogoAgent(o),
    TEAM_LOGO_FILE: L.team.path || "",
    OPPONENT_LOGO_FILE: L.opponent.path || "",
    COMPETITION_LOGO_FILE: L.competition.path,
  };
}

// הפרומפט המלא להזמנה: הנחיות קבועות + פרומפט הסגנון הנבחר
export function buildPrompt(o) {
  const vars = buildPromptVars(o);
  const stylePrompt = fillTemplate(STYLE_PROMPTS[o.styleId] || "", vars);
  return fillTemplate(MASTER_PROMPT, { ...vars, STYLE_PROMPT: stylePrompt }).replace(/\n{3,}/g, "\n\n").trim();
}
